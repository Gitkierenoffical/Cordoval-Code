// Slash menu, /plan /build /new /theme, and an image attachment sent to a model.
const { _electron: electron } = require('playwright-core');
const path = require('path'); const fs = require('fs'); const { spawnSync } = require('child_process');
const shots = path.join(__dirname, '..', 'screenshots');
(async () => {
  const proj = '/tmp/cc-composer-' + Date.now(); fs.mkdirSync(proj); spawnSync('git', ['init', '-q'], { cwd: proj });
  const app = await electron.launch({ executablePath: require('electron'), args: [path.join(__dirname, '..'), '--no-sandbox', '--project=' + proj] });
  const page = await app.firstWindow(); page.on('pageerror', e => console.log('pageerror', e.message));
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900));
  await page.waitForTimeout(7000);
  const r = {};
  await page.fill('#composer-input', '/'); await page.type('#composer-input', 'p'); await page.waitForTimeout(800);
  r.menuItems = await page.$$eval('.slash-item .slash-name', e => e.map(x => x.textContent));
  await page.screenshot({ path: path.join(shots, '15-slash-menu.png') });
  await page.fill('#composer-input', '/plan'); await page.press('#composer-input', 'Enter'); await page.press('#composer-input', 'Enter').catch(() => {}); await page.waitForTimeout(800);
  r.plan = await page.evaluate(() => document.getElementById('btn-agent-plan').classList.contains('is-active') || document.getElementById('btn-agent-plan').getAttribute('aria-pressed') === 'true');
  await page.fill('#composer-input', '/build'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(800);
  r.build = await page.evaluate(() => document.getElementById('btn-agent-build').classList.contains('is-active') || document.getElementById('btn-agent-build').getAttribute('aria-pressed') === 'true');
  const before = await page.$$eval('.session-item', e => e.length);
  await page.fill('#composer-input', '/new'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(2500);
  r.newSession = (await page.$$eval('.session-item', e => e.length)) > before;
  await page.fill('#composer-input', '/theme'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(800);
  r.theme = await page.evaluate(() => document.documentElement.dataset.theme);
  await page.fill('#composer-input', '/theme'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(500);
  if (process.env.MODEL) await page.selectOption('#model-picker', process.env.MODEL);
  await page.setInputFiles('#attach-input', '/tmp/test-image.png'); await page.waitForTimeout(800);
  r.chips = await page.$$eval('#composer-attachments > *', e => e.length);
  await page.fill('#composer-input', 'What is the main colour of the attached image? Answer in one word.');
  await page.press('#composer-input', 'Enter');
  await page.waitForTimeout(3000);
  for (let i = 0; i < 60 && await page.isVisible('#btn-stop'); i++) await page.waitForTimeout(2000);
  r.reply = (await page.$$eval('.message', e => e.map(x => x.textContent))).pop().slice(-200);
  await page.screenshot({ path: path.join(shots, '16-attachment.png') });
  console.log('[composer]', JSON.stringify(r));
  await app.close();
})();
