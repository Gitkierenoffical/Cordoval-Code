// Slash menu, /plan /build /new /theme, and an image attachment sent to the model.
const L = require('./lib');
const fs = require('fs'); const path = require('path'); const os = require('os'); const { spawnSync } = require('child_process');
(async () => {
  const proj = L.tmp('composer'); spawnSync('git', ['init', '-q'], { cwd: proj });
  const img = path.join(os.tmpdir(), 'cc-test-image.png'); require('./fixtures/red-png')(img);
  const { app, page } = await L.launch(proj);
  const r = {};
  await page.fill('#composer-input', '/'); await page.type('#composer-input', 'p'); await page.waitForTimeout(600);
  const items = await page.$$eval('.slash-item .slash-name', e => e.map(x => x.textContent));
  r.menu = items.includes('/plan');
  await L.shot(page, '15-slash-menu.png');
  await page.fill('#composer-input', '/plan'); await page.press('#composer-input', 'Enter'); await page.press('#composer-input', 'Enter').catch(() => {}); await page.waitForTimeout(600);
  r.plan = await page.evaluate(() => document.getElementById('btn-agent-plan').classList.contains('is-active'));
  await page.fill('#composer-input', '/build'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(600);
  r.build = await page.evaluate(() => document.getElementById('btn-agent-build').classList.contains('is-active'));
  const before = await page.$$eval('.session-item', e => e.length);
  await page.fill('#composer-input', '/new'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(1500);
  r.newSession = (await page.$$eval('.session-item', e => e.length)) > before;
  await page.fill('#composer-input', '/theme'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(600);
  r.theme = (await page.evaluate(() => document.documentElement.dataset.theme)) === 'dark';
  await page.fill('#composer-input', '/theme'); await page.press('#composer-input', 'Enter'); await page.waitForTimeout(400);
  await page.setInputFiles('#attach-input', img); await page.waitForTimeout(600);
  r.chip = (await page.$$eval('#composer-attachments > *', e => e.length)) === 1;
  await L.send(page, 'What is the main colour of the attached image? Answer in one word.');
  await L.waitIdle(page);
  const msgs = await L.messages(page);
  r.imageSent = msgs.some(m => m.info.role === 'user' && m.parts.some(p => p.type === 'file' && /^image\//.test(p.mime)));
  r.reply = /Red/.test((await page.$$eval('.message', e => e.map(x => x.textContent))).pop());
  await L.shot(page, '16-attachment.png');
  await app.close();
  L.report('composer', r, { items });
})().catch(e => { console.error(e); process.exit(1); });
